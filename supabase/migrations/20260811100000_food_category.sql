-- Категория товара — 11.08.2026
--
-- Бот собрал «обед» из творога, йогурта и снова творога. Без категории он не
-- видит, что это одно и то же. Теперь `search_shop_products_v1` возвращает
-- поле `category`, а промпт запрещает брать два товара одной категории.
--
-- Две ловушки, найденные на реальных названиях:
--   * «Овощной салат с огурцами, помидорами и сметаной» попадал в молочное,
--     потому что «сметан» есть в названии. Категорию задаёт главное слово,
--     поэтому сначала смотрим первые три слова и только потом всё название.
--   * «Батончик протеиновый» попадал в хлеб: основа «батон» есть в слове
--     «батончик». Снеки проверяются раньше хлеба; «Батон нарезной» остаётся
--     хлебом, потому что в списке снеков его нет.

create or replace function public.food_category_match(_text text)
returns text
language sql
immutable
set search_path = public
as $$
  select case
    when n ~ '(^|[^a-я])(кур|индей|говяд|свин|телят|ветчин|колбас|сосиск|бекон|карбонад|буженин|паштет|рыб|тунец|лосос|сельд|скумбри|форел|креветк|краб|яйц)' then 'белок'
    when n ~ '(^|[^a-я])(творог|йогурт|кефир|молок|сыр|ряженк|снежок|айран|сметан|простокваш|творожн|сырок)' then 'молочное'
    when n ~ '(^|[^a-я])(шоколад|конфет|печен|батончик|чипс|вафл|пряник|мармелад|мороженое|пастил|зефир|халв)' then 'снек'
    when n ~ '(^|[^a-я])(хлеб|лаваш|булоч|батон|хлебц|тортиль|лепешк|круассан|сэндвич|багет|пита|бутерброд)' then 'хлеб'
    when n ~ '(^|[^a-я])(рис|гречк|макарон|паста|булгур|кускус|картоф|пюре|киноа|чечевиц|фасол|нут|перловк|овсян|каша|мюсли|гранол)' then 'гарнир'
    when n ~ '(^|[^a-я])(огурц|огурец|помидор|томат|салат|капуст|морков|перец|овощ|зелен|авокадо|редис|свекл)' then 'овощи'
    when n ~ '(^|[^a-я])(банан|яблок|груш|апельсин|мандарин|киви|виноград|персик|ягод|фрукт|слив|абрикос|хурм|гранат)' then 'фрукты'
    when n ~ '(^|[^a-я])(орех|миндал|фундук|кешью|арахис|семечк|фисташк|семена)' then 'орехи'
    when n ~ '(^|[^a-я])(вода|сок|чай|кофе|напиток|морс|лимонад|кола|квас|компот)' then 'напиток'
    else 'прочее'
  end
  from (select lower(replace(coalesce(_text,''), 'ё', 'е')) as n) t;
$$;

create or replace function public.food_category_ru(_name text)
returns text
language sql
immutable
set search_path = public
as $$
  select coalesce(
    nullif(public.food_category_match(
      array_to_string((string_to_array(btrim(coalesce(_name,'')), ' '))[1:3], ' ')
    ), 'прочее'),
    public.food_category_match(_name)
  );
$$;

revoke all on function public.food_category_match(text) from public, anon, authenticated;
revoke all on function public.food_category_ru(text) from public, anon, authenticated;
