-- Утренний план каждый день строился для шести тестовых chat_id.
--
-- В `premium_context_snapshots` с начала августа лежали шесть строк от ранних
-- прогонов: 9002, 900002, 123456789, 999000111, 999000333, 999999996.
-- Проверено 24.08 — это не люди:
--   * ни одной записи в `subscription_lifecycle`;
--   * ни одного приёма пищи;
--   * ни одного апдейта Telegram за всё время, то есть чатов не существует;
--   * снимок не обновлялся 21–24 дня, тогда как у трёх настоящих подписчиков
--     он обновляется ежедневно — значит обновление контекста их и не трогает,
--     и после удаления они не вернутся.
--
-- Что это стоило каждое утро: шесть лишних проходов, шесть строк мусора в
-- `premium_daily_plans` и шесть попыток отправки в несуществующий чат.
--
-- И это было не только шумом. До 21.08 у `SEND Morning Plan` не было обработки
-- ошибки, поэтому неудачная отправка останавливала выполнение — то есть
-- тестовые строки были той же миной, что и разметка Telegram, только тише.
--
-- Условие намеренно описывает признаки, а не перечисляет id: перечисление
-- устареет, а признаки останутся верными. Настоящий подписчик под него не
-- подходит ни одним из трёх условий.
delete from public.premium_context_snapshots s
 where not exists (select 1 from public.subscription_lifecycle l where l.chat_id = s.chat_id)
   and not exists (select 1 from public.meals m where m.chat_id = s.chat_id)
   and s.refreshed_at < now() - interval '20 days';

-- Уже созданные планы этих chat_id не трогаю: это история, вреда от неё нет,
-- а удаление строк — действие необратимое и здесь ничем не оправданное.
