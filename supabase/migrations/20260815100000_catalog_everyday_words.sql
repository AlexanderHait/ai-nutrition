-- Каталог начинает находиться по обычным словам.
--
-- Проблема, найденная 15.08.2026 прогоном реальных запросов через
-- lookup_food_catalog_v3: из 18 повседневных слов каталог находил 5.
-- «огурцы», «яйца», «гречка», «рис», «макароны», «картошка», «творог»,
-- «кефир», «молоко», «сметана», «котлета куриная» — не находилось ничего,
-- и каждая такая позиция уходила к модели за выдуманным числом.
--
-- Причин ровно две, и обе не в функции поиска.
--
-- 1. Имена в каталоге записаны справочным порядком слов: «Гречка, варёная»,
--    «Рис белый, варёный», «Яйцо куриное», «Куриная грудка, готовая».
--    Человек пишет «гречка», «рис», «яйца», «грудка». Совпадения нет.
--    Русские окончания добивают остальное: «огурцы» против «огурец» это две
--    правки, а допуск опечатки — одна. «Помидоры» находились случайно,
--    потому что там правка ровно одна.
--
-- 2. Базовые молочные продукты лежали со статусом provisional, а поиск по
--    названию принимает только verified и official (карточка Б-03).
--    То есть данные были, но бот их не видел.
--
-- Правим данными, а не функцией поиска: lookup_food_catalog_v3 — самая
-- нагруженная функция проекта (карточка Б-01), и трогать её ради окончаний
-- нельзя. Синонимы для того и существуют.

-- ---------------------------------------------------------------------------
-- 1. Базовые продукты становятся видимыми
-- ---------------------------------------------------------------------------
-- Повышаются ТОЛЬКО упаковочные продукты с указанной жирностью: там число
-- определено спецификацией продукта, а не рецептом. Каждое проверено дважды —
-- калории сходятся с БЖУ (расхождение до 5%) и значение попадает в
-- межквартильный диапазон реальных этикеток из среза barcode_off:
--
--   Творог 5%    121  · 150 товаров, медиана ровно 121
--   Творог 9%    159  · арифметика по 9% жира даёт 155.8
--   Кефир 2,5%    53  ·  35 товаров, диапазон 37–56
--   Молоко 2,5%   52  · 159 товаров, диапазон 53–63
--   Сметана 15%  162  ·  59 товаров, диапазон 160–204
--   Майонез 67%  627  · арифметика по 67% жира даёт 625.8
--   Йогурт греч. 73  · 125 товаров, диапазон 71–95
--
-- Приготовленные блюда (картофельное пюре, овсяная каша, жареный картофель,
-- борщ) НЕ повышаются: их калорийность зависит от рецепта, а не от продукта.
-- Показывать такое с галочкой значит выдавать догадку за факт — ровно то,
-- против чего написана карточка Ф-03. Они остаются provisional и продолжают
-- идти к модели с пометкой «⚠️ проверь».
--
-- trust_score 85: выше provisional (60), но ниже выверенного справочника (92)
-- и тем более официального сайта (100) — настоящая этикетка обязана
-- перебивать типичное значение категории.
update public.food_catalog
   set verification_status = 'verified',
       source_type        = 'reference',
       trust_score        = 85,
       confidence         = 0.92,
       metadata = coalesce(metadata, '{}'::jsonb) || jsonb_build_object(
         'promoted_at', '2026-08-15',
         'promoted_reason', 'staple with a stated fat percentage; kcal reconcile with macros within 5% and the value sits inside the interquartile range of matching real product labels in the barcode_off slice')
 where id in (87, 88, 89, 90, 91, 124, 125)
   and verification_status = 'provisional';

-- ---------------------------------------------------------------------------
-- 2. Синонимы: как человек пишет -> что лежит в каталоге
-- ---------------------------------------------------------------------------
-- Синоним срабатывает только на полное совпадение нормализованной строки,
-- поэтому «картошка» ведёт на варёный картофель, а «картошка жареная»,
-- «молоко простоквашино» и «творог exponenta вишня» не затрагиваются вовсе.
--
-- Сознательно НЕ добавлены неоднозначные слова: «хлеб» (белый или ржаной),
-- «масло» (сливочное или оливковое), «сыр», «курица», «рыба», «паста»,
-- «каша», «орехи», «грибы».
--
-- Отдельно НЕ добавлена «овсянка»: в каталоге лежат только сухие хлопья
-- (379 ккал), а человек этим словом называет сваренную кашу (~70 ккал).
-- Синоним завысил бы тарелку впятеро — это та же ошибка «упаковка вместо
-- порции», что и с пачкой печенья.
