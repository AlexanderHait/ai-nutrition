-- Магазинный каталог стал находиться по названию — строго и только однозначно.
--
-- Зачем: 5584 позиции Open Food Facts находились только по штрих-коду, а зрение
-- читает код далеко не всегда. 07.08 бот распознал «Alpen Gold Белый шоколад Миндаль
-- и Кокос» — товар, который лежит в каталоге, — и всё равно взял вес на глаз и КБЖУ
-- из веба.
--
-- Точное совпадение имён тут не спасает: зрение пишет «Белый шоколад Миндаль и Кокос»,
-- в каталоге «шоколад белый с миндалем и кокосовой стружкой». А обычный нечёткий поиск
-- по крауд-данным опасен — именно поэтому эта область изначально из поиска исключена.
--
-- Компромисс — НАМЕРЕННО СТРОГОЕ правило, отдельный тип совпадения `shop_name`:
--   * в запросе не меньше трёх содержательных слов (от 3 букв) — «Клубничное» не пройдёт;
--   * КАЖДОЕ слово запроса должно найтись в названии, сравнение по основам
--     (у слова отбрасывается до двух последних букв, но не короче четырёх) —
--     иначе русская морфология ломает сравнение: «миндаль» не является началом «миндалем»;
--   * подходить должна РОВНО ОДНА запись каталога, иначе отказ.
-- Опечатки и частичные совпадения для этой области по-прежнему запрещены.
--
-- Замер: 8 нераспознанных позиций (худший реальный случай, чек) — 208 мс.
--
-- Полный текст функции — в миграции, применённой через apply_migration
-- `lookup_v3_shop_name_stems`; здесь фиксируется только смысл изменения,
-- чтобы история в репозитории не расходилась с базой.
--
-- Проверено после применения:
--   «Alpen Gold Белый шоколад Миндаль и Кокос» -> «Шоколад белый с миндалем и
--       кокосовой стружкой», 541 ккал/100 г, упаковка 85 г, match_type = shop_name
--   «Клубничное»                        -> нет совпадения (мало слов)
--   «Шоколад Alpen Gold»                -> нет совпадения (подходит несколько)
--   «Шоколад белый Alpen Gold с фундуком» -> нет совпадения (выдуманная комбинация)
--   «Шефролл острый», «Огурец», «Байтсы средние» -> exact, как и раньше
