-- Родительный падеж: «250 г творога», «пара огурцов», «3 яйца».
--
-- Утренняя правка научила каталог находиться по именительному падежу
-- («творог», «огурцы», «яйца»). Но человек пишет еду и в родительном:
-- «250 г творога», «немного риса», «пара огурцов», «5 яиц». Допуск опечатки
-- в одну правку такие формы не берёт — «огурцов» от «огурец» отличается на три.
--
-- Правим данными, а не поиском: lookup_food_catalog_v3 не трогаем (карточка Б-01).
-- Синоним срабатывает только на полное совпадение строки, поэтому брендовые
-- и составные запросы он не затрагивает.
--
-- Неоднозначные слова по-прежнему не добавлены: «хлеба», «масла», «сыра»,
-- «курицы», «рыбы», «каши», «орехов», «грибов». И «овсяных хлопьев» — по той же
-- причине, что и «овсянка»: в каталоге лежат сухие хлопья (379 ккал), а человек
-- этим словом чаще называет сваренную кашу.
insert into public.food_catalog_aliases (alias_normalized, food_catalog_id)
select public.normalize_food_query_v2(a.alias), a.target
from (values
  -- молочное
  ('творога', 87), ('кефира', 91), ('молока', 90), ('сметаны', 124), ('майонеза', 125),
  -- гарниры и крупы
  ('риса', 94), ('гречки', 95), ('макарон', 96), ('картошки', 99), ('картофеля', 99),
  ('чечевицы', 103), ('нута', 104), ('фасоли', 105), ('кускуса', 102),
  -- белок
  ('яиц', 86), ('куриной грудки', 77), ('грудки', 77), ('куриного бедра', 78),
  ('индейки', 79), ('говядины', 80), ('свинины', 81), ('лосося', 82), ('трески', 84),
  ('креветок', 85), ('тунца', 83),
  -- овощи и фрукты
  ('огурцов', 111), ('огурца', 111), ('помидоров', 110), ('помидора', 110),
  ('яблок', 107), ('яблока', 107), ('бананов', 7), ('банана', 7), ('апельсинов', 108),
  ('моркови', 112), ('шампиньонов', 114), ('клубники', 296), ('голубики', 256),
  -- прочее
  ('миндаля', 119), ('грецких орехов', 120), ('мёда', 122), ('сахара', 123)
) a(alias, target)
join public.food_catalog t on t.id = a.target and t.is_active
  and t.verification_status in ('verified', 'official')
on conflict (alias_normalized) do nothing;
