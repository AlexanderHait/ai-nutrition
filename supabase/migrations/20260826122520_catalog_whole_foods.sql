-- «Арбуз» в каталоге уже был (id 273), но со статусом `provisional` и
-- источником `learned` — то есть выученной догадкой модели, невидимой для
-- поиска по названию. Значение при этом совпало со справочным (30 ккал),
-- поэтому строку правим на месте, а не плодим дубль: одно имя — одна запись.
--
-- Остальные `learned`-записи (Сыр 400, Сосиски 278, Чебурек 200, Салат Оливье,
-- Жареный картофель) НЕ повышаются: это ровно тот класс «догадка выдаётся за
-- факт», против которого написано правило Ф-03. Они остаются невидимыми для
-- поиска, и такие позиции по-прежнему идут к модели с пометкой «проверь».
update public.food_catalog
   set display_name = 'Арбуз',
       kcal_per_100 = 30, prot_per_100 = 0.6, fat_per_100 = 0.15, carb_per_100 = 7.6,
       typical_grams = 300,
       source = 'generic_seed | standard food composition',
       catalog_scope = 'common', source_type = 'reference',
       trust_score = 92, verification_status = 'verified', confidence = 0.99
 where normalized_name = 'арбуз' and verification_status = 'provisional';

