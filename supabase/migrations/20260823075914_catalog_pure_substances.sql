-- Чистые вещества в каталог: там, где калорийность задана спецификацией.
--
-- Разбор дневника 23.08 показал, что модель отвечает на такие позиции своим
-- дежурным «не знаю» — 180 ккал на 100 г при Б 8 / Ж 7 / У 20:
--
--   «Фруктоза» 30 г  -> 54 ккал  (на деле ~120: сахар это 4 ккал/г)
--   «Мальтодектрин» 60 г -> 108 ккал (на деле ~228)
--
-- Это ровно тот класс, который правило Б-09 разрешает заводить в каталог:
-- число задано составом продукта, а не рецептом. Составные блюда (пицца,
-- шницель, каша с мясом) по-прежнему нельзя — там решает повар.
--
-- Что проверялось перед добавлением (по нашим же данным, а не по памяти):
-- срез Open Food Facts, только этикетки настоящего чистого вещества
-- (у > 90, ж < 1, б < 1 для сахаров; ж > 95 для масел):
--
--   сахара и крахмалы — 18 этикеток, медиана 395 ккал, углеводы 98 г
--     («Сахар-песок» 398/99.8, «Сахар белый» 400/100 ×4, «Сахарная пудра» 400/99)
--   масла — 29 этикеток, медиана 900 ккал, жир 99.9 г, разброс 898–927
--     (подсолнечное отдельно: 9 этикеток, все ровно 899 / 99.9)
--
-- Добавляются только позиции, у которых калорийность сходится с составом
-- арифметически (4 ккал/г углеводов, 9 ккал/г жира) И подтверждена этикетками.
--
-- СОЗНАТЕЛЬНО НЕ ДОБАВЛЕНО:
--   * крахмал — этикетка (381) и арифметика по углеводам (364) расходятся на 5%,
--     плюс кукурузный и картофельный различаются. Пусть отвечает модель с пометкой.
--   * глюкоза, декстроза — безводная и моногидрат различаются на 9%.
--   * сироп, протеин, изолят — зависят от бренда, спецификации нет.
--   * «масло» без уточнения — сливочное (717) и растительное (899) отличаются
--     вчетверо, это ровно та неоднозначность, которую запрещает Б-09.
insert into public.food_catalog (
  normalized_name, display_name, kcal_per_100, prot_per_100, fat_per_100, carb_per_100,
  typical_grams, source, use_count, confidence, catalog_scope, source_type,
  trust_score, verification_status, is_active
)
values
  -- 9 этикеток подсолнечного масла в срезе — все ровно 899 / жир 99.9.
  ('масло подсолнечное','Масло подсолнечное', 899, 0, 99.9, 0, 10,
   'generic_seed | standard food composition', 1, 0.99, 'common', 'reference', 92, 'verified', true),
  -- Этикетка «Сахарная пудра» из среза: 400 ккал, углеводы 99.
  ('сахарная пудра','Сахарная пудра', 400, 0, 0, 99, 10,
   'generic_seed | standard food composition', 1, 0.99, 'common', 'reference', 92, 'verified', true),
  -- Чистая фруктоза: 99.8 г углеводов × 4 = 399 ккал, сходится точно.
  ('фруктоза','Фруктоза', 399, 0, 0, 99.8, 10,
   'generic_seed | standard food composition', 1, 0.99, 'common', 'reference', 92, 'verified', true),
  -- Мальтодекстрин: стандартная этикетка 95 г углеводов × 4 = 380 ккал.
  ('мальтодекстрин','Мальтодекстрин', 380, 0, 0, 95, 30,
   'generic_seed | standard food composition', 1, 0.99, 'common', 'reference', 92, 'verified', true),
  -- Соль калорий не содержит вовсе. Без записи бот подставил бы догадку.
  ('соль','Соль', 0, 0, 0, 0, 2,
   'generic_seed | standard food composition', 1, 0.99, 'common', 'reference', 92, 'verified', true)
on conflict (normalized_name) do nothing;

-- Синонимы: как человек пишет -> что лежит в каталоге.
-- Совпадение только по полной строке, поэтому брендовые и составные запросы
-- («печенье на фруктозе») эти синонимы не перехватывают.
insert into public.food_catalog_aliases (alias_normalized, food_catalog_id)
select a.alias, f.id
  from (values
    -- Растительное масло в России это почти всегда подсолнечное, а разброс
    -- между растительными маслами (884–899) меньше 2% — синоним безопасен.
    ('подсолнечное масло','масло подсолнечное'),
    ('масло растительное','масло подсолнечное'),
    ('растительное масло','масло подсолнечное'),
    ('пудра сахарная','сахарная пудра'),
    ('фруктозы','фруктоза'),
    -- Опечатка, которую владелец реально написал боту 15.08.
    ('мальтодектрин','мальтодекстрин'),
    ('мальтодекстрина','мальтодекстрин'),
    ('мальтодектрина','мальтодекстрин'),
    ('соли','соль')
  ) as a(alias, target)
  join public.food_catalog f on f.normalized_name = a.target and f.is_active
on conflict (alias_normalized) do nothing;
