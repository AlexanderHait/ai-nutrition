import { describe, expect, it } from "vitest";
import { dayKey, mealDay } from "@/lib/data";

// Сутки питания идут с 00:00 до 23:59 по Москве — 04:00 в Нячанге (UTC+7).
// Решение владельца 13.10.2026; до этого день начинался в 03:00 МСК.
const at = (iso: string) => new Date(iso);

describe("граница суток питания", () => {
  it("вечер остаётся своим днём", () => {
    expect(dayKey(at("2026-08-11T18:00:00+03:00"))).toBe("2026-08-11");
    expect(dayKey(at("2026-08-11T23:59:00+03:00"))).toBe("2026-08-11");
  });

  it("с полуночи по Москве начинается новый день", () => {
    expect(dayKey(at("2026-08-12T00:00:00+03:00"))).toBe("2026-08-12");
    expect(dayKey(at("2026-08-12T00:30:00+03:00"))).toBe("2026-08-12");
    expect(dayKey(at("2026-08-12T02:59:00+03:00"))).toBe("2026-08-12");
  });

  it("в Нячанге день начинается в 04:00", () => {
    expect(dayKey(at("2026-10-14T03:59:00+07:00"))).toBe("2026-10-13");
    expect(dayKey(at("2026-10-14T04:00:00+07:00"))).toBe("2026-10-14");
    expect(dayKey(at("2026-10-14T06:30:00+07:00"))).toBe("2026-10-14");
  });

  it("mealDay доверяет дню из базы, а без него считает сам", () => {
    // База уже посчитала — берём как есть.
    expect(mealDay({ eaten_at: "2026-08-12T00:30:00+03:00", eaten_day: "2026-08-11" })).toBe("2026-08-11");
    // Дня из базы нет — считаем по тому же правилу.
    expect(mealDay({ eaten_at: "2026-08-11T23:30:00+03:00", eaten_day: "" as unknown as string })).toBe("2026-08-11");
    expect(mealDay({ eaten_at: "2026-08-12T00:30:00+03:00", eaten_day: "" as unknown as string })).toBe("2026-08-12");
  });
});
